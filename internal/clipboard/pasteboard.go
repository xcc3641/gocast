package clipboard

import (
	"errors"
	"io/fs"
	"os"
	"strings"
)

// ErrFileMissing means a file of the entry has been moved or deleted:
// the entry is not put on the pasteboard.
var ErrFileMissing = errors.New("clipboard: a file has been moved or deleted")

// Pasteboard is the system pasteboard as the history uses it. The system
// one is SystemPasteboard; tests use a fake.
type Pasteboard interface {
	// ChangeCount is a number that changes whenever the pasteboard's
	// contents change. It must be cheap: the watcher asks for it twice a
	// second.
	ChangeCount() int
	// Types lists the native type identifiers on the pasteboard, without
	// reading any data.
	Types() []string
	// Read reads the contents the history keeps: file paths, or the plain
	// text with its RTF and HTML, or else an image as PNG.
	Read() (Content, error)
	// Write replaces the contents with c: its files, or its text with the
	// RTF and HTML it has (and a URL type for a link), or its image.
	Write(c Content) error
}

// Markers that apps put on the pasteboard to say its contents should not
// be kept (nspasteboard.org), with older equivalents some apps still use.
var skipTypes = []string{
	"org.nspasteboard.ConcealedType",
	"org.nspasteboard.TransientType",
	"org.nspasteboard.AutoGeneratedType",
	"com.agilebits.onepassword",
	"de.petermaurer.TransientPasteboardType",
	"com.typeit4me.clipping",
	"Pasteboard generator type",
	"net.antelle.keeweb",
}

// Skipped reports whether pasteboard types mark the contents as
// confidential, transient or generated, not to be kept.
func Skipped(types []string) bool {
	for _, t := range types {
		for _, s := range skipTypes {
			if strings.EqualFold(t, s) {
				return true
			}
		}
	}
	return false
}

// DefaultIgnoredApps are the bundle IDs of the apps whose copies are not
// kept, to begin with: Passwords, Keychain Access, 1Password 8 and 7,
// Bitwarden.
var DefaultIgnoredApps = []string{
	"com.apple.Passwords",
	"com.apple.keychainaccess",
	"com.1password.1password",
	"com.agilebits.onepassword7",
	"com.bitwarden.desktop",
}

// Hooks for tests: whether Gocast may post key events, and the ⌘V
// keystroke.
var (
	trusted   = AccessibilityTrusted
	keystroke = PostPasteKeystroke
)

// write puts c on the pasteboard as the store's own write: the watcher
// will not record it.
func (s *Store) write(c Content) error {
	pb := s.opts.Pasteboard
	if pb == nil {
		return ErrNoPasteboard
	}
	s.selfWriting.Add(1)
	defer s.selfWriting.Add(-1)
	if err := pb.Write(c); err != nil {
		return err
	}
	s.selfChange.Store(int64(pb.ChangeCount()))
	return nil
}

// ownChange reports whether the pasteboard's change count n comes from
// the store's own write, or whether a write is under way, so that the
// watcher leaves it alone.
func (s *Store) ownChange(n int) (own, writing bool) {
	if s.selfWriting.Load() > 0 {
		return false, true
	}
	return s.selfChange.Load() == int64(n), false
}

// CopyToPasteboard puts the entry on the pasteboard with all it holds
// (rich text keeps its RTF and HTML next to the plain text) and moves it
// to the top. The watcher does not record it again. Files that are no
// longer there make it ErrFileMissing.
func (s *Store) CopyToPasteboard(id string) error {
	c, err := s.Content(id)
	if err != nil {
		return err
	}
	for _, f := range c.Files {
		if _, err := os.Stat(f); errors.Is(err, fs.ErrNotExist) {
			return ErrFileMissing
		}
	}
	if err := s.write(c); err != nil {
		return err
	}
	return s.Touch(id)
}

// Paste puts the entry on the pasteboard, as CopyToPasteboard, then
// presses ⌘V for the user. The caller has hidden Gocast's panel and made
// the app to paste into frontmost (ActivateApp, then WaitFrontmost on a
// goroutine) first. It may be called from any goroutine.
// Without Accessibility permission it returns ErrNoAccessibility, the
// entry left on the pasteboard for the user to paste.
func (s *Store) Paste(id string) error {
	if err := s.CopyToPasteboard(id); err != nil {
		return err
	}
	return pasteNow()
}

// PasteAsPlainText is Paste with the plain text only: no formatting, a
// link as text, files as their paths one per line. Images have no text:
// ErrNoText.
func (s *Store) PasteAsPlainText(id string) error {
	e, ok := s.Get(id)
	if !ok {
		return ErrNotFound
	}
	if e.Kind == KindImage || e.Text == "" {
		return ErrNoText
	}
	if err := s.write(Content{Text: e.Text}); err != nil {
		return err
	}
	if err := s.Touch(id); err != nil {
		return err
	}
	return pasteNow()
}

func pasteNow() error {
	if !trusted() {
		return ErrNoAccessibility
	}
	return keystroke()
}
